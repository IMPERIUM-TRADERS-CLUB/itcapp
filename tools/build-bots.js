// Bundles bots-src/bots.json + the bot files into bots-data.js (the only file the website reads bots from).
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), src = path.join(root, 'bots-src');
const list = JSON.parse(fs.readFileSync(path.join(src, 'bots.json'), 'utf8')).bots;
const xml = {};
for (const b of list) {
  const f = path.join(src, b.file);
  if (!fs.existsSync(f)) { console.error('Missing bot file for "' + b.name + '": ' + b.file); process.exit(1); }
  xml[b.id] = fs.readFileSync(f, 'utf8');
}
const pub = list.map(({ file, ...rest }) => rest); // file names are not needed by the website
fs.writeFileSync(path.join(root, 'bots-data.js'),
  '/* Generated by tools/build-bots.js. Bots are loaded inside the Bot Builder only. */\n' +
  'window.ITC_BOT_XML = ' + JSON.stringify(xml) + ';\nwindow.ITC_BOT_LIST = ' + JSON.stringify(pub) + ';\n');
console.log('bots-data.js written with', list.length, 'bots');
